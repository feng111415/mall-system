package com.ruoyi.mall.domain.product;

public class MallSpecValue
{
    private Long valueId;
    private Long specId;
    private String valueName;
    private Integer sortNo;

    public Long getValueId() { return valueId; }
    public void setValueId(Long valueId) { this.valueId = valueId; }
    public Long getSpecId() { return specId; }
    public void setSpecId(Long specId) { this.specId = specId; }
    public String getValueName() { return valueName; }
    public void setValueName(String valueName) { this.valueName = valueName; }
    public Integer getSortNo() { return sortNo; }
    public void setSortNo(Integer sortNo) { this.sortNo = sortNo; }
}
